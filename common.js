function axisScores(ans){
  const sum = {}, cnt = {};
  for(const k in AX){ sum[k]=0; cnt[k]=0; }
  for(const id in ans){
    const q = qmap.get(id); if(!q || !(q.ax in AX)) continue;
    sum[q.ax] += ans[id]===0 ? 1 : -1; cnt[q.ax]++;
  }
  const out = {}; for(const k in AX) out[k] = cnt[k] ? sum[k]/cnt[k] : 0;
  return {s:out, c:cnt};
}

