function archetype(sc){
  const ranked = Object.keys(AX).filter(k => sc.c[k]).sort((x,y) => Math.abs(sc.s[y]) - Math.abs(sc.s[x]));
  const key = k => k + (sc.s[k] >= 0 ? "+" : "-");
  const main = ranked[0] ? key(ranked[0]) : "chaos+";
  const pinch = ranked[1] && sc.s[ranked[1]] !== 0 ? PINCH[key(ranked[1])] : null;
  return {key: main, emoji: TYPES[main][0], name: TYPES[main][1], desc: TYPES[main][2], pinch};
}

